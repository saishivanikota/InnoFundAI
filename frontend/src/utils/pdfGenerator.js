/**
 * 5. Export AI Innovation & Commercialization PDF
 */
export const exportAIInnovationPDF = (idea, analysisResult) => {
  const doc = new jsPDF('p', 'mm', 'a4');
  const pageWidth = doc.internal.pageSize.getWidth();
  
  addHeader(doc, 'Innovation Intelligence', 'AI Commercialization Advisory');
  
  let y = 38;
  
  doc.setFontSize(14);
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.text('AI Research Commercialization Report', 14, y);
  y += 6;
  
  // Idea box
  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(14, y, pageWidth - 28, 18, 2, 2, 'FD');
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.setFont('helvetica', 'normal');
  doc.text('EVALUATED RESEARCH IDEA:', 18, y + 5);
  doc.setFontSize(9);
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'italic');
  const truncatedIdea = idea.length > 120 ? idea.substring(0, 117) + '...' : idea;
  doc.text(`"${truncatedIdea}"`, 18, y + 12);
  
  y += 24;
  
  if (analysisResult) {
    // 1. TRL & Impact
    doc.setFontSize(11);
    doc.setTextColor(99, 102, 241);
    doc.setFont('helvetica', 'bold');
    doc.text('Technology Readiness & Potential Impact', 14, y);
    y += 5;
    
    doc.setFontSize(9);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(51, 65, 85);
    if (analysisResult.trl) {
      doc.text(`TRL Assessment: ${analysisResult.trl}`, 18, y);
      y += 5;
    }
    if (analysisResult.impact) {
      const splitImpact = doc.splitTextToSize(`Impact: ${analysisResult.impact}`, pageWidth - 36);
      doc.text(splitImpact, 18, y);
      y += splitImpact.length * 4.5;
    }
    y += 4;
    
    // 2. Commercialization Strategies
    if (analysisResult.commercialization) {
      doc.setFontSize(11);
      doc.setTextColor(99, 102, 241);
      doc.setFont('helvetica', 'bold');
      doc.text('Commercialization Recommendations', 14, y);
      y += 5;
      doc.setFontSize(9);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(51, 65, 85);
      analysisResult.commercialization.forEach(item => {
        doc.text(`• ${item}`, 18, y);
        y += 4.5;
      });
      y += 4;
    }
    
    // 3. Recommended Funding & Target Industries
    if (analysisResult.funding) {
      doc.setFontSize(11);
      doc.setTextColor(99, 102, 241);
      doc.setFont('helvetica', 'bold');
      doc.text('Matching Funding Programs', 14, y);
      y += 5;
      doc.setFontSize(9);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(51, 65, 85);
      analysisResult.funding.forEach(item => {
        doc.text(`• ${item}`, 18, y);
        y += 4.5;
      });
    }
  }
  
  addFooter(doc, 1, 1);
  doc.save(`Innovation_Advisory_Report_${new Date().toISOString().slice(0, 10)}.pdf`);
};
